export function getHealthRecordSessions(records = healthRecords) {
    return records.flatMap((record) => {
        const sessions = [record, ...(record.sessionHistory || [])];

        return sessions.map((session) => ({
            id: session.sessionId,
            sessionId: session.sessionId,
            schoolId: session.schoolId,
            fullName: session.fullName,
            role: session.role,
            department: session.department,
            kiosk: session.kiosk,
            method: session.schoolId?.startsWith("F-") ? "Email" : "Barcode",
            status: session.sessionStatus,
            healthStatus: session.healthStatus,
            recordedAt: session.recordedAt,
            measurementsCompleted: session.measurementsCompleted,
            measurementsTotal: session.measurementsTotal,
            timeline: session.timeline || [],
        }));
    });
}
